<?php

namespace App\Simulation\Domain\Vehicle\DTOs;

/**
 * VehicleDynamicsOutput DTO - Rich Command Object.
 * Immutable data transfer object for target driving values with metadata.
 * Strategies calculate target values, module applies them to VehicleState.
 * Future processors can append modifiers to the output.
 */
readonly class VehicleDynamicsOutput
{
    public function __construct(
        public float $targetSpeed, // in km/h
        public float $targetRPM,
        public int $targetGear,
        public float $targetThrottlePosition, // 0-100 percentage
        public float $targetEngineLoad, // 0-100 percentage
        public string $generatedBy, // Strategy that generated this output
        public \DateTime $generationTime, // When this output was generated
        public array $appliedModifiers, // Ordered list of modifiers applied
        public ?string $reason, // Reason for this output
    ) {}

    /**
     * Create from current vehicle state with metadata.
     */
    public static function fromCurrentState(
        float $currentSpeed,
        float $currentRPM,
        int $currentGear,
        float $currentThrottle,
        float $currentEngineLoad,
        string $generatedBy,
        ?string $reason = null,
    ): self {
        return new self(
            targetSpeed: $currentSpeed,
            targetRPM: $currentRPM,
            targetGear: $currentGear,
            targetThrottlePosition: $currentThrottle,
            targetEngineLoad: $currentEngineLoad,
            generatedBy: $generatedBy,
            generationTime: new \DateTime(),
            appliedModifiers: [],
            reason: $reason,
        );
    }

    /**
     * Add a modifier to the applied modifiers list.
     * Returns a new instance with the modifier added.
     */
    public function addModifier(string $modifier): self
    {
        return new self(
            targetSpeed: $this->targetSpeed,
            targetRPM: $this->targetRPM,
            targetGear: $this->targetGear,
            targetThrottlePosition: $this->targetThrottlePosition,
            targetEngineLoad: $this->targetEngineLoad,
            generatedBy: $this->generatedBy,
            generationTime: $this->generationTime,
            appliedModifiers: [...$this->appliedModifiers, $modifier],
            reason: $this->reason,
        );
    }

    /**
     * Get applied modifiers.
     */
    public function getModifiers(): array
    {
        return $this->appliedModifiers;
    }

    /**
     * Set reason for this output.
     * Returns a new instance with the reason set.
     */
    public function setReason(string $reason): self
    {
        return new self(
            targetSpeed: $this->targetSpeed,
            targetRPM: $this->targetRPM,
            targetGear: $this->targetGear,
            targetThrottlePosition: $this->targetThrottlePosition,
            targetEngineLoad: $this->targetEngineLoad,
            generatedBy: $this->generatedBy,
            generationTime: $this->generationTime,
            appliedModifiers: $this->appliedModifiers,
            reason: $reason,
        );
    }

    /**
     * Get reason for this output.
     */
    public function getReason(): ?string
    {
        return $this->reason;
    }

    /**
     * Get generated by.
     */
    public function getGeneratedBy(): string
    {
        return $this->generatedBy;
    }

    /**
     * Get generation time.
     */
    public function getGenerationTime(): \DateTime
    {
        return $this->generationTime;
    }

    /**
     * Convert to array.
     */
    public function toArray(): array
    {
        return [
            'target_speed' => $this->targetSpeed,
            'target_rpm' => $this->targetRPM,
            'target_gear' => $this->targetGear,
            'target_throttle_position' => $this->targetThrottlePosition,
            'target_engine_load' => $this->targetEngineLoad,
            'generated_by' => $this->generatedBy,
            'generation_time' => $this->generationTime->format('Y-m-d H:i:s.u'),
            'applied_modifiers' => $this->appliedModifiers,
            'reason' => $this->reason,
        ];
    }
}
